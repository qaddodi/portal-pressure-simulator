# The card's GPU paragraph text needs the browser's own line breaks, and the browser sets Inter at the optical size of the text (Inter's
# `opsz` axis, 14 to 32, follows the font size: styles/app.css `font-optical-sizing: auto`), where the outlines in glyph-data.js are cut at
# opsz 14 alone. At 17 px the lines the browser sets are 1.8 % narrower than glyph-data's, enough to move a break. This writes the
# advances (plain and tabular figures) and the kerning of every character the cards use, at each weight and at a few optical sizes, as
# src/ui/glyph-metrics.js, which text-gl.js interpolates between (paragraph layout: layoutParagraph). Run again when the font changes:
#
#   pip install fonttools brotli && python3 scripts/glyph-metrics.py
import json, os, sys
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import importlib.util
spec = importlib.util.spec_from_file_location('glyphs_helpers', os.path.join(os.path.dirname(os.path.abspath(__file__)), 'glyph-helpers.py'))
H = importlib.util.module_from_spec(spec); spec.loader.exec_module(H)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEIGHTS = [400, 500, 600, 700]
STOPS = [14, 16, 18, 20, 24, 32]
CHARS = [chr(c) for c in range(0x20, 0x7F)] + list('−·⋅×±–—°µ‰≥≤→’‘“”…σαβΔ ⁠̄')
FILES = ['inter-latin', 'inter-latin-ext', 'inter-greek']

def load(w, o):
    fonts = []
    for n in FILES:
        f = TTFont(os.path.join(ROOT, 'fonts/%s.woff2' % n))
        fonts.append(instantiateVariableFont(f, {'wght': w, 'opsz': o}))
    return fonts

adv, kern, tn = {}, {}, {}
for w in WEIGHTS:
    adv[w], kern[w], tn[w] = {}, {}, {}
    for si, o in enumerate(STOPS):
        fonts = load(w, o)
        names, src = {}, {}
        for ch in CHARS:
            for f in fonts:
                n = f.getBestCmap().get(ord(ch))
                if n: names[ch] = n; src[ch] = f; break
        for ch, n in names.items():
            a = src[ch]['hmtx'][n][0]
            if ch not in adv[w]: adv[w][ch] = [None] * len(STOPS)
            adv[w][ch][si] = a
        f0 = fonts[0]
        tmap = H.tnum_map(f0)
        for d in names:   # (every character the tnum feature swaps: the figures, and a full stop, comma, colon, sign, bracket or space on their pitch)
            n = tmap.get(names.get(d))
            if n:
                tn[w].setdefault(d, [None] * len(STOPS))[si] = f0['hmtx'][n][0]
        for fi, f in enumerate(fonts):
            grp = {c: n for c, n in names.items() if src[c] is f}
            kg = H.kerning(f, list(grp.values()))
            inv = {}
            for k, n in grp.items(): inv.setdefault(n, []).append(k)
            for a, row in kg.items():
                for b, v in row.items():
                    for ka in inv.get(a, []):
                        for kb in inv.get(b, []):
                            kern[w].setdefault(ka + kb, [0] * len(STOPS))[si] = v
upm = 2048
def flat(d):
    return {k: (v[0] if len(set(v)) == 1 else v) for k, v in d.items()}
data = {str(w): {'adv': flat(adv[w]), 'tnum': flat(tn[w]), 'kern': flat(kern[w])} for w in WEIGHTS}
out = ['// Generated by scripts/glyph-metrics.py from fonts/inter-*.woff2: do not edit. Inter\'s advances (plain and tabular figures) and kerning',
       '// pairs in font units at each weight and at the optical sizes in STOPS (a number: the same at every stop), for the card\'s paragraph layout (text-gl.js).',
       'export const UPM = %d;' % upm, 'export const STOPS = %s;' % json.dumps(STOPS),
       'export const METRICS = ' + json.dumps(data, separators=(',', ':'), ensure_ascii=False) + ';', '']
p = os.path.join(ROOT, 'src/ui/glyph-metrics.js')
open(p, 'w').write('\n'.join(out))
print('wrote', os.path.getsize(p), 'bytes')
