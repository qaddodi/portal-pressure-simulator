// Writes src/ui/organ-art-lite.js: the colon's and small bowel's lines from organ-art.js with fewer points, for the
// "Lighter organ art" switch (Settings, Figure performance; off by default, and nothing of it loads while off).
// Only straight-line runs (M x yLx y...) are thinned: a point is left out when it lies within TOL world units of the line
// between the points kept either side of it (Ramer-Douglas-Peucker), so the thinned line never strays more than TOL from the
// drawn one (0.05 units: a third of a CSS pixel at 6x zoom). Curves, the ends of every run and the tubes' centre lines the
// warm glows read point by point (.ob-deep) stay as they are. Kept points keep their own text, so a kept point is the same
// number. The stage sets these d values on the drawn paths, in document order, and checks each one's length first.
//
//   node scripts/organ-art-lite.mjs && npm run stamp

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { COLON_ART, BOWEL_ART } from '../src/ui/organ-art.js';

export const TOL = 0.05;

function keepOf(P, tol) {
  const keep = new Uint8Array(P.length);
  keep[0] = keep[P.length - 1] = 1;
  const stack = [[0, P.length - 1]];
  while (stack.length) {
    const [lo, hi] = stack.pop();
    const [ax, ay] = P[lo], [bx, by] = P[hi], dx = bx - ax, dy = by - ay, L2 = dx * dx + dy * dy;
    let best = -1, bi = -1;
    for (let i = lo + 1; i < hi; i++) {
      const t = L2 ? Math.max(0, Math.min(1, ((P[i][0] - ax) * dx + (P[i][1] - ay) * dy) / L2)) : 0;
      const d = Math.hypot(P[i][0] - ax - t * dx, P[i][1] - ay - t * dy);
      if (d > best) { best = d; bi = i; }
    }
    if (best > tol) { keep[bi] = 1; stack.push([lo, bi], [bi, hi]); }
  }
  return keep;
}

const RUN = /^M(-?[\d.]+ -?[\d.]+(?:L-?[\d.]+ -?[\d.]+)+)(Z?)$/;
/** A path's d with its straight runs thinned (the same text where nothing could go). */
export function thin(d, tol = TOL) {
  return d.split(/(?=M)/).map((sub) => {
    const m = sub.match(RUN);
    if (!m) return sub;
    const txt = m[1].split('L'), P = txt.map((s) => s.split(' ').map(Number));
    if (P.length < 3) return sub;
    const keep = keepOf(P, tol);
    return 'M' + txt.filter((_, i) => keep[i]).join('L') + m[2];
  }).join('');
}

/** The art's paths in document order: [class, d]. */
export const pathsOf = (art) => [...art.matchAll(/<path\b[^>]*>/g)].map(([tag]) => [tag.match(/ class="([^"]*)"/)?.[1] || '', tag.match(/ d="([^"]*)"/)?.[1] || '']);

/** For each art: its path count and, for each path thinned, [index, the drawn d's length, index in the shared table]. */
export function liteOf(arts = { colon: COLON_ART, bowel: BOWEL_ART }) {
  const table = [], at = new Map(), out = {};
  for (const [name, art] of Object.entries(arts)) {
    const paths = pathsOf(art), list = [];
    paths.forEach(([cls, d], i) => {
      if (cls.split(' ').includes('ob-deep')) return;
      const t = thin(d);
      if (t === d) return;
      if (!at.has(t)) { at.set(t, table.length); table.push(t); }
      list.push([i, d.length, at.get(t)]);
    });
    out[name] = { n: paths.length, list };
  }
  return { table, art: out };
}

export function liteSource() {
  const { table, art } = liteOf();
  return `// Generated by scripts/organ-art-lite.mjs from organ-art.js: do not edit. The "Lighter organ art" switch's lines: the colon's
// and small bowel's straight runs with the points that lie within ${TOL} units of their neighbours' line left out.
// LITE_ART[organ]: its art's path count, and per thinned path [index in document order, the drawn d's length, index in LITE_D].
export const LITE_D = ${JSON.stringify(table)};
export const LITE_ART = ${JSON.stringify(art)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const src = liteSource();
  writeFileSync(new URL('../src/ui/organ-art-lite.js', import.meta.url), src);
  console.log('organ-art-lite.js', src.length, 'bytes');
}
