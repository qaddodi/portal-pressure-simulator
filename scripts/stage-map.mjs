// The map of createStage()'s closure (PR-09 step 2 / refactor plan H1): which of its variables each of its functions reads or writes, so a
// thread picks an extraction from facts: a block of functions that share variables nobody else touches can move out byte for byte.
//
//   node scripts/stage-map.mjs            write docs/stage-map.md
//   node scripts/stage-map.mjs --check    print the totals only
//
// Names are matched by identifier, not by scope: a local that shadows a closure name counts as a use, so the numbers read high, never low.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'espree';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FILE = 'src/ui/stage.js';
const src = readFileSync(join(ROOT, FILE), 'utf8');
const ast = parse(src, { ecmaVersion: 'latest', sourceType: 'module', loc: true });
const outer = ast.body.map((n) => (n.type === 'ExportNamedDeclaration' ? n.declaration : n)).find((n) => n?.type === 'FunctionDeclaration' && n.id.name === 'createStage');
if (!outer) throw new Error('createStage not found in ' + FILE);

const patNames = (p) => (!p ? [] : p.type === 'Identifier' ? [p.name] : p.type === 'ObjectPattern' ? p.properties.flatMap((q) => patNames(q.value || q.argument))
  : p.type === 'ArrayPattern' ? p.elements.flatMap(patNames) : p.type === 'AssignmentPattern' ? patNames(p.left) : p.type === 'RestElement' ? patNames(p.argument) : []);

const vars = new Map();   // name → { line, kind }
const units = [];         // { name, line, lines, node }  one per top-level function in the closure
for (const n of outer.body.body) {
  if (n.type === 'VariableDeclaration') {
    for (const d of n.declarations) {
      const fn = d.init && (d.init.type === 'ArrowFunctionExpression' || d.init.type === 'FunctionExpression');
      for (const name of patNames(d.id)) vars.set(name, { line: n.loc.start.line, kind: fn ? 'fn' : n.kind });
      if (fn) units.push({ name: d.id.name, line: n.loc.start.line, lines: n.loc.end.line - n.loc.start.line + 1, node: d.init });
    }
  } else if (n.type === 'FunctionDeclaration') {
    vars.set(n.id.name, { line: n.loc.start.line, kind: 'fn' });
    units.push({ name: n.id.name, line: n.loc.start.line, lines: n.loc.end.line - n.loc.start.line + 1, node: n });
  } else if (n.type === 'ClassDeclaration') vars.set(n.id.name, { line: n.loc.start.line, kind: 'class' });
}

const idsIn = (node) => {   // every identifier read or written below node (property names and keys left out)
  const out = new Set();
  const walk = (x, parent, key) => {
    if (!x || typeof x.type !== 'string') return;
    if (x.type === 'Identifier') {
      const prop = parent && ((parent.type === 'MemberExpression' && key === 'property' && !parent.computed) || (parent.type === 'Property' && key === 'key' && !parent.computed && !parent.shorthand)
        || (parent.type === 'MethodDefinition' && key === 'key'));
      if (!prop) out.add(x.name);
      return;
    }
    for (const k of Object.keys(x)) {
      if (k === 'loc' || k === 'range' || k === 'start' || k === 'end') continue;
      const v = x[k];
      if (Array.isArray(v)) v.forEach((c) => walk(c, x, k)); else if (v && typeof v === 'object') walk(v, x, k);
    }
  };
  walk(node, null, '');
  return out;
};

const uses = new Map([...vars.keys()].map((v) => [v, []]));   // variable → [unit names]
const touches = new Map();                                    // unit → [variable names]
for (const u of units) {
  const mine = [...idsIn(u.node)].filter((i) => vars.has(i) && i !== u.name);
  touches.set(u.name, mine);
  for (const i of mine) uses.get(i).push(u.name);
}
// State = the closure's non-function variables.
const state = [...vars].filter(([, v]) => v.kind !== 'fn' && v.kind !== 'class').map(([name, v]) => ({ name, ...v, users: uses.get(name) }));
const hot = [...state].sort((a, b) => b.users.length - a.users.length);
const only = state.filter((s) => s.users.length <= 3);

const totals = `${state.length} state variables, ${units.length} functions, ${src.split('\n').length} lines in ${FILE}`;
if (process.argv.includes('--check')) { console.log(totals); process.exit(0); }

const md = [];
md.push('# createStage() state map', '', `Generated by \`node scripts/stage-map.mjs\` from \`${FILE}\`. ${totals}. Names are matched by identifier, not scope, so counts read high, never low.`, '',
  'How to use it: an extraction is a set of functions whose state is used by few others. The tables below give that, so the first push of a plan can move code out byte for byte (PR-09).', '',
  '## The most shared state (the hardest to move: touch it last)', '', '| variable | line | used by |', '|---|---|---|');
for (const s of hot.slice(0, 40)) md.push(`| \`${s.name}\` | ${s.line} | ${s.users.length} |`);
md.push('', '## State owned by three functions or fewer (a candidate sits here: move the variable with its users)', '', '| variable | line | used by |', '|---|---|---|');
for (const s of only.filter((x) => x.users.length).sort((a, b) => a.line - b.line)) md.push(`| \`${s.name}\` | ${s.line} | ${s.users.join(', ')} |`);
md.push('', '## Biggest functions and how much state each reaches', '', '| function | line | lines | state variables reached |', '|---|---|---|---|');
for (const u of [...units].sort((a, b) => b.lines - a.lines).slice(0, 60)) md.push(`| \`${u.name}\` | ${u.line} | ${u.lines} | ${touches.get(u.name).filter((n) => vars.get(n).kind !== 'fn').length} |`);
md.push('', `State never used by a function at the top of the closure: ${state.filter((s) => !s.users.length).length} (read only inside nested code or by the closure body itself).`, '');
writeFileSync(join(ROOT, 'docs/stage-map.md'), md.join('\n'));
console.log('docs/stage-map.md written: ' + totals);
