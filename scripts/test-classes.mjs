// Classifies tests/*.test.js (production review PR-02):
//   source-regex  reads the text of src/, styles/ or index.html (readFileSync) and judges it, not the behaviour
//   behaviour     imports a module from src/ and calls it, reads no source text
//   other         neither (data checks, tooling tests)
// rules-lint.mjs uses sourceRegexTests() to forbid NEW source-regex tests: scripts/source-regex-tests.json lists the ones that exist today and
// may only shrink (convert a test to behaviour, or move its rule into rules-lint, then take it off the list).
//
//   node scripts/test-classes.mjs            print the counts
//   node scripts/test-classes.mjs --write    write scripts/source-regex-tests.json and docs/test-classes.md
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TESTS = join(ROOT, 'tests');
const READS_SRC = /readFileSync\([^)]*(?:\.\.\/)?(?:src|styles)\/|readFileSync\([^)]*index\.html|readFileSync\(\s*new URL\(\s*['"`]\.\.\/(?:src|styles)\/|readFileSync\(\s*new URL\(\s*['"`]\.\.\/index\.html/;
const READS_STAGE = /from\s*['"]\.\/stage-src\.js['"]/;
const IMPORTS_SRC = /^import[^;]*from\s*['"]\.\.\/src\//m;

export function classify(text) {
  if (READS_SRC.test(text) || READS_STAGE.test(text)) return 'source-regex';
  if (IMPORTS_SRC.test(text)) return 'behaviour';
  return 'other';
}
export function classes() {
  const out = { 'source-regex': [], behaviour: [], other: [] };
  for (const n of readdirSync(TESTS).filter((f) => f.endsWith('.test.js')).sort()) out[classify(readFileSync(join(TESTS, n), 'utf8'))].push(n);
  return out;
}
export const sourceRegexTests = () => classes()['source-regex'];

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const c = classes();
  const line = `source-regex ${c['source-regex'].length}, behaviour ${c.behaviour.length}, other ${c.other.length}`;
  console.log(line);
  if (process.argv.includes('--write')) {
    writeFileSync(join(ROOT, 'scripts/source-regex-tests.json'), JSON.stringify({
      note: 'Tests that judge the text of src/, styles/ or index.html. No new ones (rules-lint): test behaviour, or put the rule in scripts/rules-lint.mjs with a one-line reason. This list may only shrink: a test that no longer reads source leaves it in the same commit (node scripts/test-classes.mjs --write).',
      files: c['source-regex'],
    }, null, 1).replace(/\n {2,}"/g, '\n "') + '\n');
    writeFileSync(join(ROOT, 'docs/test-classes.md'), `# Test classes\n\nGenerated by \`node scripts/test-classes.mjs --write\` (production review PR-02). ${line}.\n\n`
      + `- **source-regex**: judges the text of the code. Brittle: any rewording fails it, and a behaviour regression that keeps the text passes it. No new ones; convert each when its module is next touched (call the module, assert what it returns or does) or turn the rule into a lint in \`scripts/rules-lint.mjs\`. A decision such as "CARDS_AT is 0.75" is kept as a one-line policy lint with its reason.\n`
      + `- **behaviour**: imports a module from \`src/\` and calls it.\n- **other**: neither.\n\n## source-regex tests still to convert\n\n${c['source-regex'].map((n) => `- ${n}`).join('\n')}\n`);
  }
}
