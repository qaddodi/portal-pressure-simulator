// Writes src/ui/custom-shunt-paths.js: the anatomic course of every custom (stent-tool) shunt, from any portal vessel to any systemic vein.
// Each is a smooth course (one cubic, or two joined at a waypoint) found by a search that keeps off the other vessels of the plate: not
// running on top of or alongside them, crossing where it has to, passing no station, with no sharp bend. A straight line between the two
// stations ran along the cava and the hepatic artery for most of its length (57 of 92 pairs: 11 Nov 2026).
// Run after changing a vessel's course in anatomy.js (tests/shunt-routes.test.js says when), about a minute:
//
//   node scripts/gen-custom-shunt-paths.mjs

import { writeFileSync } from 'node:fs';
import { EDGES } from '../src/engine/topology.js';
import { NODE_POS } from '../src/ui/anatomy.js';
import { CurveRouter, anatomyLines, anatomyStations, cubicsToD, searchCourse } from './shunt-route-lib.mjs';

const router = new CurveRouter().reset({ lines: Object.values(anatomyLines()), stations: anatomyStations(), bounds: [310, 0, 1110, 940] });
const paths = {};
for (const e of EDGES) {
  if (e.shunt !== 'custom') continue;
  const best = searchCourse(router, NODE_POS[e.from][0], NODE_POS[e.to][0]);
  paths[e.id] = cubicsToD(best.ctl);
}
const body = Object.entries(paths).map(([id, d]) => `  ${id}: '${d}',`).join('\n');
writeFileSync('src/ui/custom-shunt-paths.js', `// Generated by scripts/gen-custom-shunt-paths.mjs from the plate's vessels in anatomy.js: do not edit.\n// The anatomic course of each custom shunt (stage-geo.js), a smooth curve from its portal station to its systemic one that keeps off the other vessels.\nexport const CUSTOM_SHUNT_PATH = {\n${body}\n};\n`);
console.log(`custom-shunt-paths.js: ${Object.keys(paths).length} courses`);
