// Makes src/ui/look-tokens.js: the look of every kind of chart piece (svg-gl.js's shared looks) under every look (Light, Soft, Dark, Navy,
// Black) on the desktop and the phone, as the page's styles compute them, so a chart placed on the GPU never asks the page for a style.
//   node scripts/gen-look-tokens.mjs [dir]       dir: the production build (default dist)
// It opens every deck, steps through every slide with the right arrow, and reads the shared looks out of svg-gl.js (exportLooks) at the end
// of each deck. A piece the table lacks is read from the page as before, so a gap costs speed, never a wrong picture.
// Run from the "Look tokens" workflow (Actions tab, Run workflow), which commits the file. Never before a push.
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { serve } from './serve.mjs';
import { launch, openPage, figureUp, watchUntil, landed, pool } from './gate-clock.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const argv = process.argv.slice(2);
const DIR = argv[0] && !argv[0].startsWith('--') ? argv[0] : 'dist';
const LOOKS = [['light', 'light', null, 'light'], ['soft', 'soft', null, 'light'], ['dark', 'dark', null, 'dark'], ['navy', 'dark', 'navy', 'dark'], ['black', 'dark', 'black', 'dark']];
const SIZES = ['desktop', 'phone'];
const first = (e) => String(e?.message || e).split('\n')[0];

const server = await serve(resolve(ROOT, DIR));
const browser = await launch(true);
const { DECKS } = await import(new URL('../src/ui/decks.js', import.meta.url));
const table = { pool: [], keys: {} }, seen = new Map();
const take = (part) => {
  for (const [h, i] of Object.entries(part.keys)) {
    const rec = JSON.stringify(part.pool[i]);
    let j = seen.get(rec); if (j === undefined) { j = table.pool.length; seen.set(rec, j); table.pool.push(part.pool[i]); }
    if (table.keys[h] !== undefined && table.keys[h] !== j) console.log(`  note: key ${h} reads two ways; the later one is kept`);
    table.keys[h] = j;
  }
};
let failed = 0;
try {
  const jobs = [];
  for (const [id, theme, palette, scheme] of LOOKS) for (const size of SIZES) for (const d of DECKS) jobs.push(async () => {
    const app = await openPage(browser, `${server.url}?script=${d.id}&slide=1`, { size, clock: false, instant: true, scheme, motion: 'reduce', init: 'window.ppsLookExport = true;' });
    try {
      await figureUp(app.page);
      await app.page.evaluate(([t, p]) => { const r = document.documentElement; r.setAttribute('data-theme', t); p ? r.setAttribute('data-palette', p) : r.removeAttribute('data-palette'); }, [theme, palette]);
      await new Promise((r) => setTimeout(r, 1500));
      const open = () => { document.querySelector('.pz-case.on')?.click(); return document.querySelector('#app')?.classList.contains('presenting'); };
      if (await watchUntil(app.page, open, null, { maxFake: 120000 }) < 0) throw new Error('the deck never opened');
      const n = d.slides?.length || d.deck?.slides?.length || 1;
      for (let w = 1; w <= n; w++) {
        if (w > 1) await app.page.keyboard.press('ArrowRight');
        if (await watchUntil(app.page, landed, w, { maxFake: 60000 }) < 0) { console.log(`  ${id} ${size} ${d.id}: slide ${w} never landed`); break; }
      }
      take(await app.page.evaluate(() => window.ppsLookExport()));
      console.log(`  ${id} ${size} ${d.id}: ${n} slides read`);
    } catch (e) { failed++; console.log(`  ${id} ${size} ${d.id}: ${first(e)}`); }
    finally { await app.close(); }
  });
  await pool(jobs, 3);
} finally { await browser.close(); server.close(); }

if (!table.pool.length) { console.log('no looks were read: the table is not written'); process.exit(1); }
const out = `// GENERATED by scripts/gen-look-tokens.mjs (the "Look tokens" workflow): do not edit by hand.
// The look of every kind of chart piece under every look (theme and palette) on the desktop and the phone, as the page's styles computed
// them, so svg-gl.js never asks the page for them. A piece not found here is read from the page as before.
// pool: [raw computed style, the look's values, the transition] for each different look; keys: the hash of a piece's shared key → its pool index.
export const LOOKS = ${JSON.stringify(table)};
`;
writeFileSync(resolve(ROOT, 'src/ui/look-tokens.js'), out);
console.log(`wrote ${table.pool.length} looks for ${Object.keys(table.keys).length} pieces (${failed} deck run(s) failed)`);
