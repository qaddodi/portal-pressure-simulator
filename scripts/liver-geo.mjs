// Writes src/ui/liver-geo-data.js: the liver's outline (sampled as the stage samples it) and the sites of its
// regenerative nodules, so the stage need not compute them on every load (see src/ui/liver-geo.js).
// Run after changing the liver's outline in anatomy.js (a unit test says when), then `npm run stamp`.
//
//   node scripts/liver-geo.mjs

import { writeFileSync } from 'node:fs';
import { chromium } from 'playwright';
import { serve } from './serve.mjs';

const server = await serve('.');
const browser = await chromium.launch(process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : {});
const page = await browser.newPage();
await page.goto(server.url + 'scripts/');
const geo = await page.evaluate(async () => {
  const { ORGANS } = await import('/src/ui/anatomy.js');
  const { strHash, nodularSites } = await import('/src/ui/liver-geo.js');
  const d = ORGANS.find((o) => o.id === 'liver').d;
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  const p = document.createElementNS('http://www.w3.org/2000/svg', 'path');
  p.setAttribute('d', d); svg.append(p); document.body.append(svg);
  const L = p.getTotalLength(), n = 360, pts = [];
  for (let i = 0; i < n; i++) { const q = p.getPointAtLength((L * i) / n); pts.push([q.x, q.y]); }
  return { key: strHash(d), L, pts: pts.flat(), sites: nodularSites(pts).flat().map((v) => Math.round(v * 1000) / 1000) };
});
await browser.close(); server.close?.();
writeFileSync('src/ui/liver-geo-data.js', `// Generated by scripts/liver-geo.mjs from the liver's outline in anatomy.js: do not edit.\n/* eslint-disable no-loss-of-precision */ // (the browser's own values, kept exact)\n// key: the outline's hash; L: its length; pts: 360 points along it (x, y); sites: the nodules' sites (x, y).\nexport const LIVER_GEO = ${JSON.stringify(geo)};\n`);
console.log(`liver-geo-data.js: ${geo.pts.length / 2} outline points, ${geo.sites.length / 2} sites, key ${geo.key}`);
process.exit(0);
