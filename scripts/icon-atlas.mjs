// Icon atlas: draws every icon of the icon art (scripts/icon-art.html) once, here, into three PNG masks (one per line weight)
// and writes styles/icons.css with each icon's cell. The page never draws an SVG icon: an icon is an element whose
// mask is a cell of the atlas, painted in its own colour (currentColor), a bitmap the GPU composites like any other.
//
//   node scripts/icon-atlas.mjs     rewrites brand/icons/icons-{r,s,b}.png, brand/icons/mark.png, styles/icons.css and index.html's --pps-mark
//
// Weights (24-unit art): r 1.7 (the 20 px bar icons, --ic-w-m), s 2.1 (16 px icons, --ic-w-s), b 2.5 (tick marks and the bold few).
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const art = readFileSync(join(ROOT, 'scripts/icon-art.html'), 'utf8');
const syms = [...art.matchAll(/<symbol id="i-([a-z0-9-]+)" viewBox="0 0 24 24">([\s\S]*?)<\/symbol>/g)].map((m) => ({ id: m[1], body: m[2] }));
const COLS = 10, ROWS = Math.ceil(syms.length / COLS), CELL = 72;
export const WEIGHTS = { r: 1.7, s: 2.1, b: 2.5 };

const EXE = process.env.CHROMIUM || (existsSync('/opt/pw-browsers/chromium') ? '/opt/pw-browsers/chromium' : '');
const browser = await chromium.launch(EXE ? { executablePath: EXE } : {});
const page = await browser.newPage({ viewport: { width: COLS * CELL, height: ROWS * CELL }, deviceScaleFactor: 1 });
mkdirSync(join(ROOT, 'brand/icons'), { recursive: true });
for (const [k, w] of Object.entries(WEIGHTS)) {
  const cells = syms.map((s, i) => `<svg viewBox="0 0 24 24" width="${CELL}" height="${CELL}" style="position:absolute;left:${(i % COLS) * CELL}px;top:${Math.floor(i / COLS) * CELL}px">${s.body}</svg>`).join('');
  await page.setContent(`<!doctype html><html><body style="margin:0;background:transparent"><div id="a" style="position:relative;width:${COLS * CELL}px;height:${ROWS * CELL}px;color:#000;fill:none;stroke:currentColor;stroke-width:${w};stroke-linecap:round;stroke-linejoin:round">${cells}</div></body></html>`);
  await page.locator('#a').screenshot({ path: join(ROOT, `brand/icons/icons-${k}.png`), omitBackground: true });
}
// The brand mark (no tile): one PNG, inlined in index.html (the boot screen shows it before anything else has loaded).
const mark = art.match(/<template id="mark">([\s\S]*?)<\/template>/)[1].replace('<svg ', '<svg width="192" height="192" ');
await page.setViewportSize({ width: 192, height: 192 });
await page.setContent(`<!doctype html><html><body style="margin:0;background:transparent"><div id="m" style="width:192px;height:192px">${mark}</div></body></html>`);
const markPng = await page.locator('#m').screenshot({ path: join(ROOT, 'brand/icons/mark.png'), omitBackground: true });
await browser.close();
const html = readFileSync(join(ROOT, 'index.html'), 'utf8');
const markUrl = `--pps-mark: url("data:image/png;base64,${markPng.toString('base64')}");`;
if (!/--pps-mark: url\("data:image\/png;base64,[A-Za-z0-9+/=]*"\);/.test(html)) throw new Error('index.html has no --pps-mark declaration to fill');
writeFileSync(join(ROOT, 'index.html'), html.replace(/--pps-mark: url\("data:image\/png;base64,[A-Za-z0-9+/=]*"\);/, markUrl));

const css = [
  '/* Generated by scripts/icon-atlas.mjs from scripts/icon-art.html: do not edit. Each icon is a cell of the atlas mask. */',
  `.ic { display: inline-block; flex: none; width: 1em; height: 1em; background-color: currentColor; -webkit-mask-image: url("../brand/icons/icons-r.png"); mask-image: url("../brand/icons/icons-r.png"); -webkit-mask-size: ${COLS * 100}% ${ROWS * 100}%; mask-size: ${COLS * 100}% ${ROWS * 100}%; -webkit-mask-repeat: no-repeat; mask-repeat: no-repeat; -webkit-mask-position: calc(var(--ix) * 100% / ${COLS - 1}) calc(var(--iy) * 100% / ${ROWS - 1}); mask-position: calc(var(--ix) * 100% / ${COLS - 1}) calc(var(--iy) * 100% / ${ROWS - 1}); }`,
  ...syms.map((s, i) => `.ic-${s.id} { --ix: ${i % COLS}; --iy: ${Math.floor(i / COLS)}; }`),
].join('\n') + '\n';
writeFileSync(join(ROOT, 'styles/icons.css'), css);
console.log(`icon atlas: ${syms.length} icons, ${COLS}x${ROWS} cells of ${CELL} px, weights ${Object.keys(WEIGHTS).join(' ')}`);
