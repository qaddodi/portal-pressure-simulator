// Makes src/ui/stop-tokens.js: the colour and opacity of every gradient stop in the figure's defs, as the page's styles compute them, for
// each look (Light, Soft, Dark, Navy, Black and System in the device's light and dark) and for the circuit view (`.stage-wrap.cmap`),
// so that painting the organs never asks the browser for a stop's style (organ-paint readGradient).
//   node scripts/gen-stop-tokens.mjs            write src/ui/stop-tokens.js
//   node scripts/gen-stop-tokens.mjs --check    measure the page again and fail where the table disagrees (or lacks a stop)
// It runs the real app (scripts/shoot.mjs openApp: headless Chromium on the GPU path). tests/stop-tokens.test.js (in npm test, no
// browser) fails when the style rules or tokens the stops read change, so this is run again when it does.
import { writeFileSync } from 'node:fs';
import { openApp } from './shoot.mjs';
import { stopHash } from './stop-inputs.mjs';

const ROOT = new URL('../', import.meta.url);
const OUT = new URL('src/ui/stop-tokens.js', ROOT);
const LOOKS = [['light', 'light', null], ['soft', 'soft', null], ['dark', 'dark', null], ['navy', 'dark', 'navy'], ['black', 'dark', 'black'], ['sys-light', null, null], ['sys-dark', null, null]];

/** Every stop of the page's defs under every look, in the circuit view and not: { sig: { look+cmap: [css colour, opacity] } }. */
async function measure(page) {
  const out = {};
  for (const cmap of [0, 1]) {
    await page.evaluate((c) => window.pps.store.set({ view: c ? 'circuit' : 'anatomic' }), cmap);
    await page.waitForFunction((c) => !!document.querySelector('.stage-wrap.cmap') === !!c, cmap);
    for (const [id, theme, palette] of LOOKS) {
      await page.emulateMedia({ colorScheme: id === 'sys-dark' || theme === 'dark' ? 'dark' : 'light' });
      await page.evaluate(([t, p]) => { const r = document.documentElement; t ? r.setAttribute('data-theme', t) : r.removeAttribute('data-theme'); p ? r.setAttribute('data-palette', p) : r.removeAttribute('data-palette'); }, [theme, palette]);
      const stops = await page.evaluate(() => [...document.querySelectorAll('defs stop')].map((st) => {
        const cs = getComputedStyle(st);
        return [[st.getAttribute('class') || '', st.getAttribute('style') || '', st.getAttribute('stop-color') || '', st.getAttribute('stop-opacity') || ''].join('|'), cs.stopColor, cs.stopOpacity];
      }));
      for (const [sig, c, o] of stops) {
        const m = (out[sig] ||= {}), k = `${id}${cmap ? '+c' : ''}`, v = [c, parseFloat(o) || 0];
        if (m[k] && (m[k][0] !== v[0] || m[k][1] !== v[1])) throw new Error(`the stop "${sig}" computes two ways under ${k}: ${m[k]} and ${v}: its style depends on something the table does not key by`);
        m[k] = v;
      }
    }
  }
  return out;
}

const app = await openApp({ device: 'mac', theme: 'light', query: '' });
let out;
try { await app.freeze(); out = await measure(app.page); } finally { await app.close(); }
const sigs = Object.keys(out).sort();
const col = (sig, k) => out[sig][k] || null;
// The looks that differ anywhere are columns; one that matches another everywhere is that other's (Black and Dark, System and Light or Dark).
const names = LOOKS.map(([id]) => id), cols = [], index = {};
for (const id of names) {
  const same = cols.findIndex((c) => sigs.every((s) => JSON.stringify(col(s, c)) === JSON.stringify(col(s, id))));
  if (same >= 0) index[id] = same; else { index[id] = cols.length; cols.push(id); }
}
const flat = (sig, suffix) => cols.flatMap((c) => col(sig, c + suffix) || [null, 0]).map((v) => (v === null ? '' : v));
const stops = {}, cmap = {};
for (const s of sigs) {
  stops[s] = flat(s, '');
  const c = flat(s, '+c');
  if (JSON.stringify(c) !== JSON.stringify(stops[s])) cmap[s] = c;
}
const json = (o) => (Object.keys(o).length ? `{\n${Object.entries(o).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},   // colour-exempt: computed from styles/tokens.css`).join('\n')}\n}` : '{}');
const text = `// GENERATED by scripts/gen-stop-tokens.mjs (npm run gen:stops): do not edit by hand.
// The colour and opacity of every gradient stop in the figure's defs, as the page's styles compute them, for each look and for the
// circuit view, so that organ-paint readGradient never asks the browser for a stop's style. A stop is named by its signature:
// class|style|stop-color|stop-opacity, as the markup gives it. Each row is [colour, opacity] for each column of STOP_COLS in turn.
// tests/stop-tokens.test.js fails when the style rules these read change, until this is made again.

/** The hash of the style rules and tokens the stops are computed from (scripts/stop-inputs.mjs). */
export const STOP_HASH = ${JSON.stringify(stopHash(ROOT, sigs))};
/** The looks that compute differently (each other look is one of these: STOP_LOOK). */
export const STOP_COLS = ${JSON.stringify(cols)};
/** Every look (Light, Soft, Dark, Navy, Black, and System as the device's light or dark) → its column. */
export const STOP_LOOK = ${JSON.stringify(index)};
/** Each stop's colour and opacity per column, in the anatomy. */
export const STOPS = ${json(stops)};
/** The stops that compute differently in the circuit view (.stage-wrap.cmap), per column. */
export const STOPS_CMAP = ${json(cmap)};
`;
if (process.argv.includes('--check')) {
  const { STOPS: T, STOPS_CMAP: TC, STOP_LOOK: L, STOP_COLS: C } = await import(`${OUT.href}?${Date.now()}`);
  let bad = 0;
  for (const s of sigs) for (const id of names) for (const cm of [0, 1]) {
    const v = out[s][`${id}${cm ? '+c' : ''}`];
    if (!v) continue;
    const row = (cm && TC[s]) || T[s];
    if (!row) { console.error('missing stop', s); bad++; break; }
    const i = L[id] * 2;
    if (row[i] !== v[0] || row[i + 1] !== v[1]) { console.error(`differs: ${s} ${id}${cm ? ' circuit' : ''}: table ${row[i]} ${row[i + 1]}, page ${v}`); bad++; }
  }
  console.log(bad ? `${bad} mismatches` : `ok: ${sigs.length} stops, ${C.length} columns (${C.join(', ')}), ${Object.keys(TC).length} differ in the circuit view`);
  process.exit(bad ? 1 : 0);
}
writeFileSync(OUT, text);
console.log(`wrote src/ui/stop-tokens.js: ${sigs.length} stops, columns ${cols.join(', ')}, ${Object.keys(cmap).length} differ in the circuit view`);
