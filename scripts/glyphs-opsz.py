# The GPU's numbers at the page's own optical size. Inter sets text at opsz = the font size in px (14 to 32, font-optical-sizing: auto), but
# glyph-data.js is cut at opsz 14 alone, so a big number the GPU drew changed shape and width when the page's own text took over after it
# settled. This cuts the characters a readout is made of at a few more optical sizes (text-gl.js picks the nearest one for the size) and
# writes src/ui/glyph-data-opsz.js, fetched only where text above 17 px is drawn. Run again when the font changes:
#
#   pip install fonttools brotli && python3 scripts/glyphs-opsz.py
import json, os
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
import importlib.util

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEIGHTS = [400, 500, 600, 700]
STOPS = [20, 24, 32]   # (14 is glyph-data.js)
CHARS = list('0123456789 .,:+-/%()') + list('−·×°')
_spec = importlib.util.spec_from_file_location('glyph_helpers', os.path.join(os.path.dirname(os.path.abspath(__file__)), 'glyph-helpers.py'))
_h = importlib.util.module_from_spec(_spec); _spec.loader.exec_module(_h)
data = {}
for o in STOPS:
    data[o] = {}
    for w in WEIGHTS:
        f = instantiateVariableFont(TTFont(os.path.join(ROOT, 'fonts/inter-latin.woff2')), {'wght': w, 'opsz': o})
        cmap = f.getBestCmap(); gs = f.getGlyphSet(); hmtx = f['hmtx']; tn = _h.tnum_map(f)
        def glyph(name):
            pen = SVGPathPen(gs, lambda v: ('%.1f' % v).rstrip('0').rstrip('.'))
            gs[name].draw(pen)
            return [hmtx[name][0], pen.getCommands()]
        chars, tab, names = {}, {}, {}
        for ch in CHARS:
            n = cmap.get(ord(ch))
            if not n: continue
            chars[ch] = glyph(n); names[ch] = n
        for ch in CHARS:
            n = tn.get(names.get(ch))
            if n: tab[ch] = glyph(n)
        kern_g = _h.kerning(f, list(names.values()))
        inv = {}
        for k, n in names.items(): inv.setdefault(n, []).append(k)
        kern = {}
        for a, row in kern_g.items():
            for b, v in row.items():
                for ka in inv.get(a, []):
                    for kb in inv.get(b, []): kern[ka + kb] = v
        data[o][w] = {'chars': chars, 'tnum': tab, 'kern': kern}
out = ['// Generated by scripts/glyphs-opsz.py from fonts/inter-latin.woff2: do not edit. The characters of a readout cut at the optical sizes',
       '// above opsz 14 (glyph-data.js has 14), by weight: advances and outlines in font units, y up (text-gl.js picks the nearest size).',
       'export const OPSZ_STOPS = %s;' % json.dumps(STOPS),
       'export const GLYPHS_OPSZ = ' + json.dumps(data, separators=(',', ':'), ensure_ascii=False) + ';', '']
p = os.path.join(ROOT, 'src/ui/glyph-data-opsz.js')
open(p, 'w').write('\n'.join(out))
print('wrote', p, os.path.getsize(p), 'bytes')
